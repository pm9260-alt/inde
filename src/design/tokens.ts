interface TypeStyle {
  fontFamily: string;
  fontSize: number;
  lineHeight: number;
  letterSpacing: number;
}

const type = (
  family: string,
  size: number,
  lineHeightRatio: number,
  trackingEm: number,
): TypeStyle => ({
  fontFamily: family,
  fontSize: size,
  lineHeight: Math.round(size * lineHeightRatio * 10) / 10,
  letterSpacing: Math.round(size * trackingEm * 100) / 100,
});

